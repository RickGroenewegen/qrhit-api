#!/usr/bin/env node
/**
 * The languages, countries and currencies of QRSong! live in three files in
 * this repo, src/data/shared/{locales,markets,currencies}.json. This copies
 * them into the website and the scan app and writes, in all three repos, a
 * typed module over them (shared-data.generated.ts) that the code imports.
 *
 *   node scripts/sync-shared-data.mjs           write the copies
 *   node scripts/sync-shared-data.mjs --check   change nothing; exit 1 on drift
 *
 * --check also fails when growth.config.json in the website lacks a site
 * language in `pillars.blog.locales` (blog + reviews) or `pillars.ux.locales`.
 * The unit tests run it when the sibling repos are checked out next to this
 * one. See NEW_LANGUAGE.md.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const API_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_DIR = join(API_ROOT, 'src/data/shared');
const FILES = ['locales.json', 'markets.json', 'currencies.json'];
const CHECK = process.argv.includes('--check');

const TARGETS = [
  { repo: API_ROOT, dir: 'src/data/shared', copy: false },
  { repo: resolve(API_ROOT, '../qrhit'), dir: 'src/data/shared', copy: true },
  { repo: resolve(API_ROOT, '../qrhit-app'), dir: 'src/app/shared-data', copy: true },
];

const read = (file) => readFileSync(join(SOURCE_DIR, file), 'utf8');
const sources = Object.fromEntries(FILES.map((f) => [f, read(f)]));
const locales = JSON.parse(sources['locales.json']).locales;
const markets = JSON.parse(sources['markets.json']).markets;
const currencies = JSON.parse(sources['currencies.json']).currencies;

const union = (codes) => codes.map((c) => `'${c}'`).join(' | ');

const generated = `// Generated by qrhit-api/scripts/sync-shared-data.mjs from locales.json,
// markets.json and currencies.json next to this file. Do not edit: change the
// JSON in qrhit-api/src/data/shared/ and run the script.

import localesJson from './locales.json';
import marketsJson from './markets.json';
import currenciesJson from './currencies.json';

export type LocaleCode = ${union(locales.map((l) => l.code))};
export type MarketCode = ${union(markets.map((m) => m.code))};
export type CurrencyCode = ${union(currencies.map((c) => c.code))};

export interface SharedLocale {
  code: LocaleCode;
  /** English name: LLM prompts, translate.js, and the \`langs.<name in lower case>\` key. */
  name: string;
  /** The name in the language itself: the language pickers. */
  nativeName: string;
  /** flagcdn.com country code. */
  flag: string;
  /** BCP-47 tag when the route code is not one (jp → ja). */
  htmlLang?: string;
  /** Codes a browser or device uses for this language (nb, nn → no). */
  aliases?: string[];
  ogLocale?: string;
  /** Mail greeting. */
  greeting?: string;
  /** Apple Music storefront. */
  storefront?: string;
  /** The market a speaker most likely buys from: payment methods. */
  country: MarketCode | null;
  /** The market whose dates the occasion pages use, when not \`country\`. */
  occasionCountry?: MarketCode;
  /** The currency this language's pages show, whoever crawls them. */
  currency: CurrencyCode | null;
  /** The countries the shipping page suggests first. */
  shippingCountries: string[];
  /** Mollie checkout locale (nl/de/fr vary by country in code). */
  mollieLocale: string | null;
  /** npm package with hyphenation patterns for card titles. */
  hyphenation: string | null;
  /** How the playlist prompt names the language and its market. */
  aiDescription?: string;
  /** Part of the product feed offer id; never renumber. */
  feedNumber?: number;
  /** Served by qrsong.io. */
  site: boolean;
  /** Spoken by the scan app. */
  app: boolean;
}

export interface SharedMarket {
  code: MarketCode;
  name: string;
  /** The currency a visitor from here gets unless they pick one (EUR when absent). */
  currency?: CurrencyCode;
  /** The playlist languages /playlists shows here, besides the international lists. */
  locales?: LocaleCode[];
  /** Mollie methods, most popular first; the checkout shows them in this order. */
  paymentMethods?: string[];
  /** Methods the homepage trust strip leaves out here. */
  notOnBadges?: string[];
  /** An occasion-calendar market. */
  occasions?: boolean;
  /** The language of this country's product feed, when it has one. */
  feed?: LocaleCode;
}

export interface SharedCurrency {
  code: CurrencyCode;
  /** Decimals a price is shown with. */
  decimals: number;
  /** Converted amounts round to a multiple of this (0: to the cent). */
  snap: number;
  /** Mollie methods that accept it. A method no currency lists is EUR-only. */
  methods: string[];
}

/** Every language, the unserved (site: false) ones included. */
export const LOCALES = localesJson.locales as unknown as readonly SharedLocale[];
/** The languages qrsong.io is served in, in menu order. */
export const SITE_LOCALES = LOCALES.filter((l) => l.site);
/** The languages the scan app speaks. */
export const APP_LOCALES = LOCALES.filter((l) => l.app);
export const MARKETS = marketsJson.markets as unknown as readonly SharedMarket[];
/** Payment methods for a visitor without a known country. */
export const PAYMENT_FALLBACK = marketsJson.fallback.paymentMethods as readonly string[];
/** In the currency switcher's order. */
export const CURRENCIES = currenciesJson.currencies as unknown as readonly SharedCurrency[];
`;

const problems = [];
const writes = [];

for (const target of TARGETS) {
  const dir = join(target.repo, target.dir);
  if (!existsSync(target.repo)) {
    console.log(`skip ${relative(API_ROOT, target.repo)}: not checked out here`);
    continue;
  }
  const wanted = [['shared-data.generated.ts', generated]];
  if (target.copy) for (const f of FILES) wanted.push([f, sources[f]]);
  for (const [file, content] of wanted) {
    const path = join(dir, file);
    const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (current === content) continue;
    if (CHECK) problems.push(`${relative(API_ROOT, path)} is ${current === null ? 'missing' : 'out of date'}`);
    else writes.push([path, content]);
  }
}

// growth.config.json cannot import anything; it is checked instead.
const growthConfig = resolve(API_ROOT, '../qrhit/growth.config.json');
if (existsSync(growthConfig)) {
  const pillars = JSON.parse(readFileSync(growthConfig, 'utf8')).pillars ?? {};
  for (const [pillar, list] of [['blog', pillars.blog?.locales], ['ux', pillars.ux?.locales]]) {
    const missing = locales.filter((l) => l.site && !(list ?? []).includes(l.code)).map((l) => l.code);
    if (missing.length) problems.push(`growth.config.json pillars.${pillar}.locales lacks ${missing.join(', ')}`);
  }
}

for (const [path, content] of writes) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log(`wrote ${relative(API_ROOT, path)}`);
}

if (problems.length) {
  for (const p of problems) console.error(`  ${p}`);
  console.error(CHECK ? '\nRun node scripts/sync-shared-data.mjs in qrhit-api.' : '');
  process.exit(1);
}
if (CHECK) console.log('shared data in sync');
